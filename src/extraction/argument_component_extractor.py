"""
E3 Experiment: Reasoning-Aware Argument Component Extractor (v1.1)
Extracts:
  1. Central Claim (core proposition / stance)
  2. Core Reasoning (causal mechanisms, evidence, grounds)
  3. Underlying Warrant (normative principle / inferential bridge)

v1.1 Improvements:
- Protects dotted abbreviations and acronyms (e.g. D.A.R.E., U.S., U.K., A.P.A., e.g., i.e.)
  preventing spurious sentence-boundary truncations.
- Disambiguates causal conjunction "as" from prepositional "as" phrases
  (e.g. "as a fundamental principle", "as a citizen"), preventing false clause clippings.
"""

import os
import re
import hashlib
import json
from typing import Dict, List, Optional, Tuple

EXTRACTION_VERSION = "e3-v1.1-toulmin-discourse"

# Rhetorical prefixes generated by LLM viewpoint prompts
PREFIX_PATTERNS = [
    r'^(?:####\s*)?(?:[\w\s\-]+Perspective|Viewpoint|Justification|Argument)\s*::?\s*',
    r'^\*\*(?:Stance|Perspective|Summary|Reasoning)\*\*:\s*',
    r'^(?:Positive|Negative|Neutral|Supporting|Opposing)\s+Viewpoint:\s*',
]

# Common dotted abbreviations to protect during sentence splitting
ABBREVIATION_PATTERN = re.compile(
    r'\b((?:[A-Za-z]\.){2,}|e\.g\.|i\.e\.|et al\.|vs\.|etc\.)',
    re.IGNORECASE
)

# Causal, instrumental, and clausal discourse connectives
# Specifically restricts "as" to clausal usage (followed by pronouns or noun+verb)
CONNECTIVE_PATTERN = re.compile(
    r'\b('
    r'because|since|on the grounds that|in order to|so that|which leads to|resulting in|'
    r'by\s+[a-z]+ing|through\s+[a-z]+ing|'
    r'as\s+(?:it|they|this|these|there|we|he|she|[a-z]+ing|[a-z\s]+?\s+(?:is|are|was|were|can|could|will|would|have|has|had|do|does|did|tend|tends|lead|leads|demonstrate|demonstrates|show|shows))\b'
    r')',
    re.IGNORECASE
)

# Evaluative predicates linking causal reasoning to normative outcome
EVALUATIVE_PATTERN = re.compile(
    r'\b(lead to|leads to|results in|causes|promotes|fosters|enhances|undermines|prevents|violates|ensures|reduces|increases|is harmful|is beneficial|is crucial|is essential|is necessary|infringes|protects|weakens|strengthens)\b\s+(.*)',
    re.IGNORECASE
)


def compute_stable_text_id(text: str) -> str:
    """Computes a deterministic 16-character SHA-256 hash of stripped text."""
    clean = text.strip()
    return hashlib.sha256(clean.encode("utf-8")).hexdigest()[:16]


def clean_text(text: str) -> str:
    """Removes prompt scaffolding and viewpoint metadata prefixes."""
    res = text.strip()
    for pat in PREFIX_PATTERNS:
        res = re.sub(pat, '', res, flags=re.IGNORECASE)
    return res.strip()


def protect_abbreviations(text: str) -> str:
    """Replaces periods in acronyms/abbreviations with a placeholder to prevent spurious splitting."""
    return ABBREVIATION_PATTERN.sub(lambda m: m.group(0).replace('.', '__DOT__'), text)


def unprotect_abbreviations(text: str) -> str:
    """Restores periods in acronyms/abbreviations."""
    return text.replace('__DOT__', '.')


def split_sentences(text: str) -> List[str]:
    """Splits text into sentences using punctuation boundaries while protecting abbreviations."""
    cleaned = clean_text(text)
    protected = protect_abbreviations(cleaned)
    sents = [unprotect_abbreviations(s.strip()) for s in re.split(r'(?<=[.!?])\s+', protected) if s.strip()]
    return sents if sents else [cleaned]


def extract_argument_components(text: str, claim_topic: str = "") -> Dict[str, str]:
    """
    Extracts central claim, core reasoning, and underlying warrant from argumentative text.
    """
    cleaned = clean_text(text)
    sentences = split_sentences(cleaned)
    
    if not sentences or not cleaned:
        return {
            "central_claim": cleaned,
            "core_reasoning": cleaned,
            "underlying_warrant": f"Underlying principle regarding '{claim_topic}': {cleaned}"
        }
        
    lead_sentence = sentences[0]
    
    # 1. Central Claim Extraction:
    # Check if lead sentence contains internal discourse connectives splitting claim thesis from grounds
    match = CONNECTIVE_PATTERN.search(lead_sentence)
    if match and match.start() > 15:
        claim_part = lead_sentence[:match.start()].strip().rstrip(',;')
        intra_reasoning = lead_sentence[match.start():].strip()
    else:
        claim_part = lead_sentence
        intra_reasoning = ""
        
    central_claim = claim_part
    
    # 2. Core Reasoning Extraction:
    # Includes intra-sentence grounds and any subsequent explanatory/evidentiary sentences
    if len(sentences) > 1:
        elaboration = " ".join(sentences[1:])
        if intra_reasoning:
            core_reasoning = f"{intra_reasoning} {elaboration}".strip()
        else:
            core_reasoning = elaboration
    else:
        core_reasoning = intra_reasoning if intra_reasoning else lead_sentence
        
    # 3. Underlying Warrant Extraction:
    # The warrant is the inferential principle / value bridge that justifies the claim from grounds.
    eval_match = EVALUATIVE_PATTERN.search(cleaned)
    if eval_match:
        eval_phrase = eval_match.group(0).rstrip('.')
        underlying_warrant = f"Underlying warrant for '{claim_topic}': the normative principle that {eval_phrase}."
    else:
        underlying_warrant = f"Underlying warrant for '{claim_topic}': the principle that {core_reasoning} warrants {central_claim}."
        
    return {
        "central_claim": central_claim,
        "core_reasoning": core_reasoning,
        "underlying_warrant": underlying_warrant
    }


class ArgumentComponentExtractor:
    """
    Production-ready argument component extraction module.
    Provides batch and single extraction with stable caching.
    """
    def __init__(self, version: str = EXTRACTION_VERSION):
        self.version = version
        
    def extract_single(self, text: str, claim_topic: str = "", metadata: Optional[Dict] = None) -> Dict:
        stable_id = compute_stable_text_id(text)
        comps = extract_argument_components(text, claim_topic)
        record = {
            "text_id": stable_id,
            "extraction_version": self.version,
            "original_text": text,
            "claim_topic": claim_topic,
            "central_claim": comps["central_claim"],
            "core_reasoning": comps["core_reasoning"],
            "underlying_warrant": comps["underlying_warrant"]
        }
        if metadata:
            record["metadata"] = metadata
        return record
        
    def extract_batch(self, items: List[Dict[str, str]]) -> List[Dict]:
        """
        Extracts components for a list of dicts with keys 'text' and optional 'claim_topic' and 'metadata'.
        """
        results = []
        for item in items:
            t = item.get("text", "")
            c = item.get("claim_topic", "")
            m = item.get("metadata", None)
            results.append(self.extract_single(t, c, m))
        return results
